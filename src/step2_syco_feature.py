"""Step 2 paired sycophancy feature extraction from syco_dataset.jsonl.

This pipeline uses the paired responses generated by ``run_step2.sh``:

    query + sycophantic response
    query + robust response

For each response, only the first N assistant tokens are scored.  Each token's
residual activation is encoded by the SAE independently, then feature scores
are pooled over tokens in SAE-latent space with top-k mean pooling.
"""

